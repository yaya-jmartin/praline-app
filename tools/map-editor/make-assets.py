"""Builds js/assets.js: the default parchment and the app's fonts as data URLs.

The editor runs from a file:// page, where Chrome treats every other local file as another origin: a
parchment loaded with <img src> would block the export, and fonts would not load. Embedding them avoids
both. Run after changing assets/parchment.webp or the app fonts: python3 make-assets.py
"""
import base64, os

here = os.path.dirname(os.path.abspath(__file__))
fonts = os.path.join(here, '..', '..', 'app', 'assets', 'fonts')

def data(path, mime):
    with open(path, 'rb') as f:
        return 'data:%s;base64,%s' % (mime, base64.b64encode(f.read()).decode())

out = [
    '// Generated by make-assets.py: do not edit by hand.',
    'var ASSETS = {',
    '  parchment: "%s",' % data(os.path.join(here, 'assets', 'parchment.webp'), 'image/webp'),
    '  fontTitle: "%s",' % data(os.path.join(fonts, 'meaculpa.ttf'), 'font/ttf'),
    '  fontBody: "%s",' % data(os.path.join(fonts, 'fraunces_regular.ttf'), 'font/ttf'),
    '  fontBold: "%s"' % data(os.path.join(fonts, 'fraunces_semibold.ttf'), 'font/ttf'),
    '};',
]
with open(os.path.join(here, 'js', 'assets.js'), 'w') as f:
    f.write('\n'.join(out) + '\n')
